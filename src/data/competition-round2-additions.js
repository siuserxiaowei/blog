function officialSource(title, url) {
  return {
    title,
    date: ROUND2_ADDITIONS_CHECKED_AT,
    url,
    kind: 'official',
  };
}

function confirmedDeadline({
  date,
  sourceUrl,
  timezone,
  type = 'submission',
  label = '最终提交截止',
  primary = false,
}) {
  return {
    type,
    date,
    certainty: 'confirmed',
    timezone,
    label,
    primary,
    sourceUrl,
  };
}

function trackedAddition(record) {
  const sourceUrl = record.url;
  const deadlineTimezone = record.deadlineTimezone;
  const primaryDeadline = record.primaryDeadline ?? confirmedDeadline({
    date: record.deadlineISO,
    sourceUrl,
    timezone: deadlineTimezone,
    type: record.deadlineType,
    label: record.deadlineLabel,
    primary: true,
  });

  return {
    rel: 'A',
    tier: 'A',
    cat: 'AI 软件',
    recordType: 'competition',
    seriesId: null,
    parentId: null,
    fullName: record.name,
    timeline: [{ event: primaryDeadline.label, date: primaryDeadline.date, critical: true }],
    deadlines: [primaryDeadline],
    sources: [officialSource(`核验来源｜${record.name}`, sourceUrl)],
    verification: {
      status: 'verified',
      checkedAt: ROUND2_ADDITIONS_CHECKED_AT,
      sourceKind: 'official',
      linkHealth: 'reachable',
      notes: '报名资格、主截止日和奖项边界已按官方赛事页复核。',
    },
    ...record,
    primaryDeadline,
  };
}

