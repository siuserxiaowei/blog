function trackedAddition(record) {
  const primaryDeadline = record.primaryDeadline ?? {
    type: record.deadlineType ?? 'submission',
    date: record.deadlineISO,
    certainty: 'confirmed',
    timezone: record.deadlineTimezone,
    label: record.deadlineLabel ?? '作品提交截止',
    primary: true,
    sourceUrl: record.url,
  };
  const deadlines = record.deadlines ?? [primaryDeadline];
  const sources = record.sources ?? [evidenceSource(`赛事页面｜${record.name}`, record.url)];

  return {
    rel: 'A',
    tier: 'A',
    cat: 'AI 软件',
    recordType: 'competition',
    seriesId: null,
    parentId: null,
    entryStatus: 'closed',
    fullName: record.name,
    timeline: [{ event: primaryDeadline.label, date: primaryDeadline.date, critical: true }],
    sources,
    verification: {
      status: 'verified',
      checkedAt: ROUND9_ADDITIONS_CHECKED_AT,
      sourceKind: sources.some((source) => source.kind === 'official') ? 'official' : 'reported',
      linkHealth: 'reachable',
      notes: '赛事日期、资格与奖励边界已按所列来源复核；未披露字段保持 not-stated。',
    },
    curation: {
      primaryFormats: ['software-product', 'agent'],
      rewardAccessibility: 'medium',
      rewardEvidence: '以可运行的软件或 Agent 为主要交付物。',
    },
    ...record,
    deadlines,
    primaryDeadline,
    sources,
  };
}

