export const ROUND7_ADDITIONS_CHECKED_AT = '2026-08-05';

function evidenceSource(title, url, kind = 'official', date = ROUND7_ADDITIONS_CHECKED_AT) {
  return { title, date, url, kind };
}

function confirmedDeadline({ date, sourceUrl, timezone, type = 'submission', label, primary = false }) {
  return { type, date, certainty: 'confirmed', timezone, label, primary, sourceUrl };
}

function uncertainDeadline({ certainty, label, date = null, type = 'submission', timezone = 'Asia/Shanghai', primary = true, sourceUrl = null }) {
  return { type, date, certainty, timezone, label, primary, sourceUrl };
}

function trackedAddition(record) {
  const primaryDeadline = record.primaryDeadline ?? confirmedDeadline({
    date: record.deadlineISO,
    sourceUrl: record.url,
    timezone: record.deadlineTimezone,
    type: record.deadlineType,
    label: record.deadlineLabel,
    primary: true,
  });
  const deadlines = record.deadlines ?? [primaryDeadline];
  const sources = record.sources ?? [evidenceSource(`核验来源｜${record.name}`, record.url)];
  const timeline = record.timeline ?? [{ event: primaryDeadline.label, date: primaryDeadline.date ?? '日期待确认', critical: true }];

  return {
    rel: 'A',
    tier: 'A',
    cat: 'AI 软件',
    recordType: 'competition',
    seriesId: null,
    parentId: null,
    entryStatus: 'open-to-new',
    fullName: record.fullName ?? record.name,
    timeline,
    deadlines,
    sources,
    verification: {
      status: 'verified',
      checkedAt: ROUND7_ADDITIONS_CHECKED_AT,
      sourceKind: sources.some(source => source.kind === 'official') ? 'official' : 'reported',
      linkHealth: 'reachable',
      notes: '当前报名窗口、资格硬门槛、费用与奖励边界已按所列官方或权威来源复核；未披露字段保持 not-stated。',
    },
    ...record,
    timeline,
    deadlines,
    primaryDeadline,
    sources,
  };
}

