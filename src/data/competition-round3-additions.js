function officialSource(title, url) {
  return {
    title,
    date: ROUND3_ADDITIONS_CHECKED_AT,
    url,
    kind: 'official',
  };
}

function confirmedDeadline({
  date,
  sourceUrl,
  timezone,
  type = 'submission',
  label = '最终提交截止',
  primary = false,
}) {
  return {
    type,
    date,
    certainty: 'confirmed',
    timezone,
    label,
    primary,
    sourceUrl,
  };
}

function trackedAddition(record) {
  const primaryDeadline = record.primaryDeadline ?? confirmedDeadline({
    date: record.deadlineISO,
    sourceUrl: record.url,
    timezone: record.deadlineTimezone,
    type: record.deadlineType,
    label: record.deadlineLabel,
    primary: true,
  });

  return {
    rel: 'A',
    tier: 'A',
    cat: 'AI 软件',
    recordType: 'competition',
    seriesId: null,
    parentId: null,
    fullName: record.fullName ?? record.name,
    timeline: [{ event: primaryDeadline.label, date: primaryDeadline.date, critical: true }],
    deadlines: [primaryDeadline],
    sources: [officialSource(`核验来源｜${record.name}`, record.url)],
    verification: {
      status: 'verified',
      checkedAt: ROUND3_ADDITIONS_CHECKED_AT,
      sourceKind: 'official',
      linkHealth: 'reachable',
      notes: '资格、费用边界、当前可行动截止与奖励性质已按所列一手来源复核。',
    },
    ...record,
    primaryDeadline,
  };
}

