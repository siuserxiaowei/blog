function officialSource(title, url) {
  return { title, date: ROUND14_ADDITIONS_CHECKED_AT, url, kind: 'official' };
}

function trackedAddition(record) {
  const primaryDeadline = record.primaryDeadline;
  const deadlines = record.deadlines ?? [primaryDeadline];
  return {
    rel: 'A',
    tier: 'A',
    cat: '数据算法',
    recordType: 'competition',
    seriesId: null,
    parentId: null,
    fullName: record.name,
    entryStatus: 'unknown',
    verification: {
      status: 'verified',
      checkedAt: ROUND14_ADDITIONS_CHECKED_AT,
      sourceKind: 'official',
      linkHealth: 'reachable',
      notes: '赛事身份、任务、赛程、资格与奖励边界已按所列官网或官方平台复核；未披露的日期、奖金、队伍规模、费用和知识产权条款均保留为未知。',
    },
    ...record,
    deadlines,
    primaryDeadline,
    timeline: record.timeline ?? deadlines
      .filter((deadline) => deadline.date)
      .map((deadline) => ({
        event: deadline.label,
        date: deadline.date,
        critical: Boolean(deadline.primary),
      })),
    sources: record.sources ?? [officialSource(`赛事官网｜${record.name}`, record.url)],
  };
}

